export interface ArchetypeAnswerInput {
  questionId: string;
  questionText: string;
  selectedOptions?: string[];
  customText?: string;
  isSkipped?: boolean;
}

export interface ArchetypePromptInput {
  userName?: string;
  answers: ArchetypeAnswerInput[];
  stage?: 'interview' | 'report';
  finishRequested?: boolean;
}

export function buildArchetypeUserPrompt(input: ArchetypePromptInput): string {
  return JSON.stringify({
    stage: input.stage || 'report',
    user_name: input.userName || 'Искатель',
    question_count: input.answers.length,
    finish_requested: !!input.finishRequested,
    answers: input.answers.map((a, idx) => ({
      id: a.questionId || `q_${idx + 1}`,
      question: a.questionText,
      selected: a.selectedOptions || [],
      custom_reflection: a.customText || null,
      skipped: !!a.isSkipped,
    })),
  }, null, 2);
}
